"""Compare Codex's blind rebuild of the data tables with the project pipeline.

Usage (from the repo root): .venv/bin/python -I verification/compare_p4data.py

Reads verification/codex_p4data/codex_*.csv (Codex, built from the raw files and
verification/codex_p4data/SPEC.md only) and the project outputs in data/processed/ and
results/qc/. Writes verification/codex_p4data/COMPARISON.md with, per table, the number of
keys compared, keys present on one side only, and the largest absolute difference per
numeric column (relative tolerance 1e-9 counts as equal). Exit code 1 if anything differs.
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
CODEX = ROOT / "verification" / "codex_p4data"
OUT = CODEX / "COMPARISON.md"
RTOL = 1e-9


def compare(name: str, ours: pd.DataFrame, theirs: pd.DataFrame, keys: list[str],
            cols: list[str], lines: list[str]) -> bool:
    m = ours.merge(theirs, on=keys, how="outer", suffixes=("_ours", "_codex"), indicator=True)
    only_ours = int((m["_merge"] == "left_only").sum())
    only_codex = int((m["_merge"] == "right_only").sum())
    both = m[m["_merge"] == "both"]
    ok = only_ours == 0 and only_codex == 0
    lines.append(f"## {name}\n")
    lines.append(f"Keys {keys}: {len(both)} matched, {only_ours} only in ours, "
                 f"{only_codex} only in Codex.\n")
    lines.append("| column | cells | mismatches | max abs diff |")
    lines.append("|---|---|---|---|")
    for c in cols:
        a, b = both[f"{c}_ours"], both[f"{c}_codex"]
        if pd.api.types.is_numeric_dtype(a) and pd.api.types.is_numeric_dtype(b):
            a, b = a.astype(float), b.astype(float)
            nan_mismatch = a.isna() != b.isna()
            close = np.isclose(a, b, rtol=RTOL, atol=1e-12) | (a.isna() & b.isna())
            bad = int((~close | nan_mismatch).sum())
            diff = (a - b).abs().max(skipna=True)
            diff_txt = "0" if pd.isna(diff) or diff == 0 else f"{diff:.3g}"
        else:
            bad = int((a.astype(str) != b.astype(str)).sum())
            diff_txt = "n/a"
        ok = ok and bad == 0
        lines.append(f"| {c} | {len(both)} | {bad} | {diff_txt} |")
    lines.append("")
    return ok


def main() -> None:
    lines = ["# Codex blind rebuild versus the project pipeline", "",
             "Generated by `verification/compare_p4data.py`. Codex worked from the raw files and "
             "`SPEC.md` only.", ""]
    ok = True

    ours = pd.read_csv(ROOT / "data/processed/events.csv")
    theirs = pd.read_csv(CODEX / "codex_events.csv")
    ok &= compare("events", ours[["pond", "date", "t", "weight", "length", "n_rows"]], theirs,
                  ["pond", "date"], ["t", "weight", "length", "n_rows"], lines)

    q = pd.read_csv(ROOT / "results/qc/qc_counts.csv")
    q["n_invalid_missing_or_nonfinite"] = q["n_missing_raw"] + q["n_nonfinite"]
    theirs = pd.read_csv(CODEX / "codex_qc_counts.csv")
    ok &= compare("QC counts", q[["pond", "sensor", "n_values", "n_invalid_missing_or_nonfinite",
                                  "n_out_of_range", "n_flatline", "n_valid"]], theirs,
                  ["pond", "sensor"], ["n_values", "n_invalid_missing_or_nonfinite",
                                       "n_out_of_range", "n_flatline", "n_valid"], lines)

    d = pd.read_csv(ROOT / "data/processed/daily_wq.csv")
    d = d.rename(columns={"left_anchor_date": "left_anchor", "right_anchor_date": "right_anchor"})
    theirs = pd.read_csv(CODEX / "codex_daily.csv")
    for frame in (d, theirs):
        frame["left_anchor"] = frame["left_anchor"].fillna("")
        frame["right_anchor"] = frame["right_anchor"].fillna("")
    ok &= compare("daily table", d[["pond", "date", "sensor", "mean", "sd", "min", "max", "status",
                                    "left_anchor", "right_anchor"]], theirs,
                  ["pond", "date", "sensor"],
                  ["mean", "sd", "min", "max", "status", "left_anchor", "right_anchor"], lines)

    w = pd.read_csv(ROOT / "data/processed/wq_by_date.csv")
    theirs = pd.read_csv(CODEX / "codex_wq_by_date.csv")
    cols = [c for c in theirs.columns if c not in ("pond", "date")]
    missing = [c for c in cols if c not in w.columns]
    if missing:
        raise KeyError(f"columns missing in data/processed/wq_by_date.csv: {missing}")
    ok &= compare("window features by date", w[["pond", "date"] + cols], theirs,
                  ["pond", "date"], cols, lines)

    t1 = pd.read_csv(ROOT / "data/processed/t1_table.csv")
    theirs = pd.read_csv(CODEX / "codex_t1.csv").rename(columns={"eligible": "eligible_eval"})
    t1 = t1.rename(columns={"n_covered_window": "t1_n_covered_window"})
    ok &= compare("T1 eligibility", t1[["pond", "date", "t", "t1_n_covered_window", "eligible_eval"]],
                  theirs, ["pond", "date"], ["t", "t1_n_covered_window", "eligible_eval"], lines)

    t2 = pd.read_csv(ROOT / "data/processed/t2_table.csv")
    theirs = pd.read_csv(CODEX / "codex_t2.csv").rename(columns={"eligible": "eligible_eval"})
    t2 = t2.rename(columns={"n_covered_window": "t2_n_covered_window"})
    ok &= compare("T2 samples and eligibility",
                  t2[["pond", "origin_date", "target_date", "horizon", "dt_prev",
                      "t2_n_covered_window", "eligible_eval"]],
                  theirs, ["pond", "origin_date", "target_date", "horizon"],
                  ["dt_prev", "t2_n_covered_window", "eligible_eval"], lines)

    lines.append(f"Overall: {'IDENTICAL within tolerance' if ok else 'DIFFERENCES FOUND'}.")
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
